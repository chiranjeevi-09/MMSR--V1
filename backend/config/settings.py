# Cache Configuration (audit M-9 / TASK 15):
# - Production sets REDIS_URL in .env: a shared cache so login throttling
#   holds across multiple workers.
# - Local development without REDIS_URL falls back to an in-process LocMem
#   cache so nothing (throttling included) requires Redis to be installed.
#   LocMem throttling is per-process: single dev server only, never for
#   multi-worker deployments.
REDIS_URL = config('REDIS_URL', default='')
if REDIS_URL:
    CACHES = {
        'default': {
            'BACKEND': 'django_redis.cache.RedisCache',
            'LOCATION': REDIS_URL,
            'OPTIONS': {
                'CLIENT_CLASS': 'django_redis.client.DefaultClient',
            },
            'KEY_PREFIX': 'academic_pub',
            'TIMEOUT': 300,  # 5 minutes default
        }
    }
else:
    CACHES = {
        'default': {
            'BACKEND': 'django.core.cache.backends.locmem.LocMemCache',
            'LOCATION': 'mmsr-local-cache',
            'TIMEOUT': 300,
        }
    }
    # Phase 4 §10 / SECURITY-QA-REPORT M-6: a production (non-DEBUG) deployment
    # that reaches this branch has NO shared cache — login throttling counters
    # live per process and evaporate across gunicorn/uwsgi workers, so the rate
    # limits DEPLOYMENT.md relies on are effectively bypassed with `-w 4`.
    # That used to be a startup warning nobody read; it is now a hard stop, in
    # line with the DB-credential fail-fast above. Two deliberate escapes:
    #   * the test suite runs with DEBUG=False and no Redis, and must still run;
    #   * a genuine single-worker staging box may opt in explicitly with
    #     ALLOW_LOCMEM_IN_PROD=True (never set that on a multi-worker host).
    if not DEBUG:
        import sys

        running_tests = 'test' in sys.argv[:2] or os.environ.get('DJANGO_SETTINGS_TEST')
        allow_locmem = config('ALLOW_LOCMEM_IN_PROD', default=False, cast=bool)
        if not running_tests and not allow_locmem:
            raise ImproperlyConfigured(
                'REDIS_URL is required when DEBUG=False. Without a shared cache '
                'the login/reset/invitation throttles are per-worker and are '
                'multiplied by the worker count, i.e. effectively disabled. Set '
                'REDIS_URL in backend/.env (see DEPLOYMENT.md), or '
                'ALLOW_LOCMEM_IN_PROD=True for a deliberately single-worker '
                'staging box.'
            )
        if not running_tests:
            import warnings
            warnings.warn(
                'ALLOW_LOCMEM_IN_PROD is set while DEBUG=False: cache and '
                'throttle state is PER-WORKER ONLY. Safe only on a host that '
                'runs exactly one worker.', RuntimeWarning, stacklevel=1,
            )


